// ShiftPulse Ledger - Offline-First Service Worker
const CACHE_NAME = 'shiftpulse-core-v3';
const PRECACHE_ASSETS = [
  '/?app=1',
  '/',
  '/index.html',
  '/install',
  '/manifest.json',
  '/icon.svg',
  '/pwa-192x192.png',
  '/pwa-512x512.png',
  '/apple-touch-icon.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_ASSETS)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  const url = new URL(event.request.url);
  if (url.origin !== location.origin) return;

  // Never cache dynamic API gateway or local disk endpoints
  if (url.pathname.startsWith('/api/')) return;

  // Cache-first for Vite immutable hashed /assets/* bundles; network-first for HTML/navigation
  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(event.request).then((cached) => {
        if (cached) return cached;
        return fetch(event.request).then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const clone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return networkResponse;
        });
      })
    );
    return;
  }

  event.respondWith(
    fetch(event.request)
      .then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const clone = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return networkResponse;
      })
      .catch(async () => {
        const cached = await caches.match(event.request);
        if (cached) return cached;
        if (event.request.mode === 'navigate') {
          if (url.pathname === '/' && !url.search) {
            return (await caches.match('/')) || (await caches.match('/?app=1'));
          }
          return (await caches.match('/?app=1')) || (await caches.match('/index.html'));
        }
        return new Response('Offline', { status: 503, statusText: 'Offline Mode' });
      })
  );
});
